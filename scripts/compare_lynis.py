#!/usr/bin/env python3
"""Compare two Lynis reports and print a README-ready before/after table.

Usage:
    python3 scripts/compare_lynis.py reports/mail/lynis-before.dat reports/mail/lynis-after.dat
    python3 scripts/compare_lynis.py before.dat after.dat --format json

Paste the Markdown output into the "Results" section of the README.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from lynis_report import load_report  # noqa: E402


def _key(item: dict) -> tuple[str, str]:
    return (item["test_id"], item["message"])


def _delta(before, after) -> str:
    if before is None or after is None:
        return "n/a"
    d = after - before
    return f"+{d}" if d > 0 else str(d)


def compare(before: dict, after: dict) -> dict:
    bw = {_key(w) for w in before["warnings"]}
    aw = {_key(w) for w in after["warnings"]}
    bs = {_key(s) for s in before["suggestions"]}
    as_ = {_key(s) for s in after["suggestions"]}
    return {
        "hostname": after["hostname"] or before["hostname"],
        "hardening_index": {
            "before": before["hardening_index"],
            "after": after["hardening_index"],
            "delta": _delta(before["hardening_index"], after["hardening_index"]),
        },
        "warnings": {
            "before": len(before["warnings"]),
            "after": len(after["warnings"]),
            "delta": _delta(len(before["warnings"]), len(after["warnings"])),
        },
        "suggestions": {
            "before": len(before["suggestions"]),
            "after": len(after["suggestions"]),
            "delta": _delta(len(before["suggestions"]), len(after["suggestions"])),
        },
        "tests_done": {
            "before": before["tests_done"],
            "after": after["tests_done"],
            "delta": _delta(before["tests_done"], after["tests_done"]),
        },
        "resolved_warnings": sorted(bw - aw),
        "new_warnings": sorted(aw - bw),
        "resolved_suggestions": sorted(bs - as_),
        "new_suggestions": sorted(as_ - bs),
        "lynis_version": {"before": before["lynis_version"], "after": after["lynis_version"]},
        "dates": {"before": before["started"], "after": after["started"]},
    }


def _fmt(v) -> str:
    return "n/a" if v is None else str(v)


def to_markdown(result: dict, max_items: int = 15) -> str:
    hi = result["hardening_index"]
    lines = [
        f"<!-- generated by scripts/compare_lynis.py for host {result['hostname'] or '?'} -->",
        "| Metric | Before | After | Change |",
        "|---|---:|---:|---:|",
        f"| **Lynis hardening index** | {_fmt(hi['before'])} | {_fmt(hi['after'])} | **{hi['delta']}** |",
    ]
    for label, key in (("Warnings", "warnings"), ("Suggestions", "suggestions"), ("Tests performed", "tests_done")):
        r = result[key]
        lines.append(f"| {label} | {_fmt(r['before'])} | {_fmt(r['after'])} | {r['delta']} |")
    lines += [
        "",
        f"Lynis {result['lynis_version']['before'] or '?'} - before: {result['dates']['before'] or '?'}, "
        f"after: {result['dates']['after'] or '?'}",
    ]
    if result["lynis_version"]["before"] != result["lynis_version"]["after"]:
        lines.append("")
        lines.append("> Note: the two runs used different Lynis versions, so the scores are not strictly comparable.")

    def section(title: str, items: list) -> None:
        if not items:
            return
        lines.extend(["", f"**{title}** ({len(items)})", ""])
        for test_id, message in items[:max_items]:
            lines.append(f"- `{test_id or '?'}` {message}")
        if len(items) > max_items:
            lines.append(f"- ... and {len(items) - max_items} more")

    section("Resolved warnings", result["resolved_warnings"])
    section("New warnings", result["new_warnings"])
    section("Resolved suggestions", result["resolved_suggestions"])
    section("New suggestions", result["new_suggestions"])
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Before/after comparison of two lynis-report.dat files.")
    parser.add_argument("before")
    parser.add_argument("after")
    parser.add_argument("--format", choices=["md", "json"], default="md")
    parser.add_argument("-o", "--output")
    args = parser.parse_args(argv)

    for p in (args.before, args.after):
        if not Path(p).is_file():
            print(f"error: {p} not found", file=sys.stderr)
            return 2
    result = compare(load_report(args.before), load_report(args.after))
    if result["hardening_index"]["before"] is None or result["hardening_index"]["after"] is None:
        print("warning: a report has no hardening_index; was the Lynis run complete?", file=sys.stderr)

    out = json.dumps(result, indent=2, default=list) + "\n" if args.format == "json" else to_markdown(result)
    if args.output:
        Path(args.output).write_text(out, encoding="utf-8")
    else:
        sys.stdout.write(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
